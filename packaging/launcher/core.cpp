// A path written with '/' as the player sees it on this platform.
std::string Shown(std::string text) {
  std::replace(text.begin(), text.end(), '/', kSlash);
  return text;
}

bool FileExists(const fs::path& path) {
  std::error_code ec;
  return fs::is_regular_file(path, ec);
}

bool DirExists(const fs::path& path) {
  std::error_code ec;
  return fs::is_directory(path, ec);
}

uint64_t FileSize(const fs::path& path) {
  std::error_code ec;
  const uintmax_t size = fs::file_size(path, ec);
  return ec ? 0 : static_cast<uint64_t>(size);
}

uint32_t BE32(const uint8_t* p) {
  return (uint32_t(p[0]) << 24) | (uint32_t(p[1]) << 16) | (uint32_t(p[2]) << 8) | p[3];
}

// Moves a file over an existing one (the target is replaced).
bool ReplaceFileOver(const fs::path& from, const fs::path& to) {
#ifdef _WIN32
  return MoveFileExW(from.c_str(), to.c_str(), MOVEFILE_REPLACE_EXISTING | MOVEFILE_WRITE_THROUGH) != 0;
#else
  std::error_code ec;
  fs::rename(from, to, ec);
  return !ec;
#endif
}

// Moves a folder; fails when the target exists and is not empty.
bool MoveFolder(const fs::path& from, const fs::path& to) {
#ifdef _WIN32
  return MoveFileExW(from.c_str(), to.c_str(), 0) != 0;
#else
  std::error_code ec;
  fs::rename(from, to, ec);
  return !ec;
#endif
}

std::string HashFile(const fs::path& path) {
  std::ifstream in(path, std::ios::binary);
  if (!in) return {};
  Sha256 sha;
  std::vector<char> buffer(1 << 20);
  while (in.read(buffer.data(), static_cast<std::streamsize>(buffer.size())) || in.gcount() > 0) {
    sha.Add(reinterpret_cast<const uint8_t*>(buffer.data()), static_cast<size_t>(in.gcount()));
  }
  if (in.bad()) return {};
  return sha.Hex();
}

