// ================================================================ paths ==
Paths MakePaths() {
  Paths p;
#ifdef _WIN32
  std::vector<wchar_t> buffer(32768);
  const DWORD length = GetModuleFileNameW(nullptr, buffer.data(), static_cast<DWORD>(buffer.size()));
  p.launcher = fs::path(std::wstring(buffer.data(), length));
#else
  std::error_code ec;
  p.launcher = fs::read_symlink("/proc/self/exe", ec);
  if (ec || p.launcher.empty()) p.launcher = fs::current_path(ec) / kGameExeName;
#endif
  p.root = p.launcher.parent_path();
  p.resources = p.root / "resources";
  p.runtime = p.resources / "runtime";
  p.game_exe = p.runtime / kGameExeName;
  p.assets = p.resources / "assets";
  p.userdata = p.resources / "userdata";
  p.config = p.userdata / "ge.toml";
  p.logs = p.runtime / "logs";
  p.staging = p.resources / ".import";
  p.previous = p.resources / ".assets-previous";
  return p;
}

