Extras CurrentExtras(const Paths& p, const fs::path& shortcut_folder) {
  Extras e;
  std::string value;
  // fullscreen defaults to true in the runtime; ge.toml says false until changed.
  e.fullscreen = FileExists(p.config) ? (!ReadConfig(p, "fullscreen", &value) || value == "true") : false;
  e.complete = ReadConfig(p, "ge_unlock_all", &value) && value == "true";
  e.shortcut = OurShortcut(p, ShortcutPath(shortcut_folder));
  return e;
}

std::string ApplyExtras(const Paths& p, const Extras& want, const Extras& was, const fs::path& shortcut_folder,
                        const std::function<bool(const fs::path&)>& ask_replace) {
  std::string note;
  EnsureSettings(p);
  // Only the one key per extra is written; every other setting stays as it is.
  if (want.fullscreen != was.fullscreen) {
    WriteConfig(p, "fullscreen", want.fullscreen ? "true" : "false");
    Log(std::string("Extra fullscreen: ") + (want.fullscreen ? "on" : "off"));
  }
  if (want.complete != was.complete) {
    // The game re-applies the unlocks to the save while this is on; the save
    // keeps them, so switching it off later does not take anything away.
    WriteConfig(p, "ge_unlock_all", want.complete ? "true" : "false");
    Log(std::string("Extra 100% completion: ") + (want.complete ? "on" : "off"));
  }
  if (want.shortcut != was.shortcut) {
    const fs::path link = ShortcutPath(shortcut_folder);
    if (link.empty()) {
      note = "The folder for the shortcut could not be found, so no shortcut was made.";
    } else if (want.shortcut) {
      bool write = true;
      if (FileExists(link) && !OurShortcut(p, link)) write = ask_replace && ask_replace(link);
      if (!write) {
        note = std::string("A different GoldenEye 007 shortcut is already ") + kShortcutPlace +
               ", so it was left as it is.";
        Log("Shortcut: kept the existing one at " + Utf8(link));
      } else if (!WriteShortcut(p, link)) {
        note = "The shortcut could not be created.";
      } else {
        Log("Shortcut: " + Utf8(link));
      }
    } else if (OurShortcut(p, link)) {
      std::error_code ec;
      fs::remove(link, ec);
      Log("Shortcut removed.");
    }
  }
  return note;
}

void RepairShortcut(const Paths& p, const fs::path& shortcut_folder) {
  const fs::path link = ShortcutPath(shortcut_folder);
  fs::path target;
  std::string description;
  if (link.empty() || !FileExists(link) || !ReadShortcut(link, &target, &description)) return;
  // Ours (by its description), aimed at a launcher that is no longer there:
  // the folder was moved, so point it here.
  if (description != kShortcutDescription || FileExists(target)) return;
  if (!EqualsNoCase(Utf8(target.filename()), kGameExeName)) return;
  if (WriteShortcut(p, link)) Log("Shortcut updated for the moved folder.");
}

// ================================================================= game ==
bool LaunchGame(const Paths& p, const std::vector<std::string>& args, std::string* error) {
#ifdef _WIN32
  std::wstring command = Quote(p.game_exe.wstring());
  for (const std::string& arg : args) command += L" " + Quote(Widen(arg));
  STARTUPINFOW startup = {sizeof(startup)};
  PROCESS_INFORMATION process = {};
  if (!CreateProcessW(p.game_exe.c_str(), command.data(), nullptr, nullptr, FALSE, 0, nullptr, p.runtime.c_str(),
                      &startup, &process)) {
    *error = "GoldenEye 007 could not be started (error " + std::to_string(GetLastError()) + ").";
    return false;
  }
  // Let the game take the foreground from the launcher.
  AllowSetForegroundWindow(process.dwProcessId);
  CloseHandle(process.hThread);
  CloseHandle(process.hProcess);
  return true;
#else
  std::vector<std::string> strings;
  strings.push_back(p.game_exe.string());
  strings.insert(strings.end(), args.begin(), args.end());
  std::vector<char*> argv;
  for (std::string& s : strings) argv.push_back(s.data());
  argv.push_back(nullptr);
  const std::string exe = p.game_exe.string();
  const std::string dir = p.runtime.string();

  // A close-on-exec pipe tells us whether the exec worked, without waiting for the game.
  int report[2];
  if (pipe(report) != 0) {
    *error = std::string("GoldenEye 007 could not be started (") + strerror(errno) + ").";
    return false;
  }
  fcntl(report[0], F_SETFD, FD_CLOEXEC);
  fcntl(report[1], F_SETFD, FD_CLOEXEC);
  const pid_t pid = fork();
  if (pid < 0) {
    *error = std::string("GoldenEye 007 could not be started (") + strerror(errno) + ").";
    close(report[0]);
    close(report[1]);
    return false;
  }
  if (pid == 0) {
    // Own session: the game outlives the launcher's terminal or process group
    // (closing the terminal, or a desktop entry's helper reaping its group).
    setsid();
    if (chdir(dir.c_str()) == 0) execv(exe.c_str(), argv.data());
    const int code = errno;
    const ssize_t ignored = write(report[1], &code, sizeof(code));
    (void)ignored;
    _exit(127);
  }
  close(report[1]);
  int code = 0;
  ssize_t got;
  do {
    got = read(report[0], &code, sizeof(code));
  } while (got < 0 && errno == EINTR);
  close(report[0]);
  if (got == static_cast<ssize_t>(sizeof(code))) {
    waitpid(pid, nullptr, 0);
    *error = std::string("GoldenEye 007 could not be started (") + strerror(code) + ").";
    return false;
  }
  return true;
#endif
}

