// Desktop Entry string values: backslash is the escape character.
std::string DesktopEscape(const std::string& text) {
  std::string out;
  for (char c : text) {
    if (c == '\\')
      out += "\\\\";
    else if (c == '\n')
      out += "\\n";
    else
      out += c;
  }
  return out;
}

std::string DesktopUnescape(const std::string& text) {
  std::string out;
  for (size_t i = 0; i < text.size(); ++i) {
    if (text[i] == '\\' && i + 1 < text.size()) {
      const char next = text[++i];
      out += next == 'n' ? '\n' : next == 't' ? '\t' : next == 's' ? ' ' : next == 'r' ? '\r' : next;
    } else {
      out += text[i];
    }
  }
  return out;
}

// The Exec value for one program path: quoted, with the characters the
// Desktop Entry spec reserves inside quotes escaped (then string-escaped).
std::string ExecValue(const fs::path& program) {
  std::string quoted = "\"";
  for (char c : Utf8(program)) {
    if (c == '"' || c == '`' || c == '$' || c == '\\') quoted += '\\';
    if (c == '%') quoted += '%';
    quoted += c;
  }
  return DesktopEscape(quoted + "\"");
}

// The program named by an Exec value (the first, possibly quoted, word).
fs::path ExecProgram(const std::string& value) {
  const std::string text = DesktopUnescape(value);
  std::string out;
  if (!text.empty() && text[0] == '"') {
    for (size_t i = 1; i < text.size() && text[i] != '"'; ++i) {
      if (text[i] == '\\' && i + 1 < text.size()) ++i;
      out += text[i];
    }
  } else {
    out = text.substr(0, text.find_first_of(" \t"));
  }
  return fs::path(out);
}

// The Exec program and Comment of a launcher entry's [Desktop Entry] group.
bool ReadShortcut(const fs::path& link, fs::path* target, std::string* description) {
  std::string text;
  if (!ReadAll(link, &text)) return false;
  bool in_entry = false, have_exec = false;
  for (const std::string& line : SplitLines(text)) {
    if (!line.empty() && line[0] == '[') {
      in_entry = line == "[Desktop Entry]";
      continue;
    }
    if (!in_entry) continue;
    if (line.compare(0, 5, "Exec=") == 0) {
      *target = ExecProgram(line.substr(5));
      have_exec = true;
    } else if (line.compare(0, 8, "Comment=") == 0) {
      *description = DesktopUnescape(line.substr(8));
    }
  }
  return have_exec;
}

bool WriteShortcut(const Paths& p, const fs::path& link) {
  const std::string text = std::string("[Desktop Entry]\n") + "Type=Application\n" + "Name=GoldenEye 007\n" +
                           "Comment=" + kShortcutDescription + "\n" + "Exec=" + ExecValue(p.launcher) + "\n" +
                           "Path=" + DesktopEscape(Utf8(p.root)) + "\n" +
                           "Icon=" + DesktopEscape(Utf8(p.runtime / "icon.png")) + "\n" + "Terminal=false\n" +
                           "Categories=Game;\n";
  std::error_code ec;
  fs::create_directories(link.parent_path(), ec);
  if (!WriteAll(link, text)) return false;
  // A launcher on the desktop folder wants the executable bit to be trusted.
  fs::permissions(link,
                  fs::perms::owner_all | fs::perms::group_read | fs::perms::group_exec | fs::perms::others_read |
                      fs::perms::others_exec,
                  ec);
  return true;
}

bool SamePathNoCase(const fs::path& a, const fs::path& b) { return a == b; }
#endif

bool OurShortcut(const Paths& p, const fs::path& link) {
  fs::path target;
  std::string description;
  return FileExists(link) && ReadShortcut(link, &target, &description) &&
         (SamePathNoCase(target, p.launcher) || SameFile(target, p.launcher));
}

